function unitLayer(
  n: number,
  id: string,
  title: string,
  species: string[],
  fields: string[],
  nameField: string | undefined,
  geometry: LayerSource['geometry'] = 'polygon',
  defaultVisible = false,
): LayerSource {
  return {
    id,
    title,
    group: 'hunting-units',
    url: `${WILD_UNITS}/${n}`,
    geometry,
    attribution: `${ATTR_DNR} Wildlife Division`,
    minZoom: 0,
    defaultVisible,
    fields,
    nameField,
    species,
  };
}

